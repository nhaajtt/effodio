let current: Record<Key, string> = en;
export let locale = "en";

export function setLanguage(choice: "auto" | "en" | "vi"): void {
  const wanted = choice === "auto" ? (navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en") : choice;
  locale = wanted;
  current = wanted === "vi" ? vi : en;
  document.documentElement.lang = wanted;
}

export function t(key: Key, values: Record<string, string | number> = {}): string {
  let out = current[key] ?? en[key] ?? key;
  for (const [name, value] of Object.entries(values)) out = out.replace(`{${name}}`, String(value));
  return out;
}

